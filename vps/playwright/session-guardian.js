#!/usr/bin/env node
/**
 * VOYO Session Guardian
 *
 * Runs every 6h via cron. For each Chrome profile:
 *   1. Opens the profile via Playwright persistent context
 *   2. Visits youtube.com/feed/subscriptions (auth-gated)
 *   3. Checks login state (avatar present = alive, sign-in button = dead)
 *   4. Exports fresh cookies to Netscape file for yt-dlp
 *   5. Posts session_ok or cookie_login_lost to Supabase
 *
 * Does NOT attempt re-login — VPS datacenter IPs trigger Google 2FA/CAPTCHA.
 * Session keep-alive (visiting YouTube while logged in) prevents the inactivity
 * expiry that causes most bot-checks.
 *
 * Deploy:
 *   cd /opt/voyo/playwright && npm install
 *   npx playwright install chromium --with-deps
 *   cron: 0 * /6 * * * root /opt/voyo/playwright/run-guardian.sh  (remove space after *)
 */

'use strict';

const { chromium } = require('playwright');
const fs   = require('fs');
const path = require('path');
const https = require('https');

// ── Config ────────────────────────────────────────────────────────────────────

const PROFILES = [
  { name: 'chrome-profile-001', dir: '/opt/voyo/chrome-profile-001', cookieFile: '/opt/voyo/cookies-001.txt' },
  { name: 'chrome-profile-002', dir: '/opt/voyo/chrome-profile-002', cookieFile: '/opt/voyo/cookies-002.txt' },
  { name: 'chrome-profile-003', dir: '/opt/voyo/chrome-profile-003', cookieFile: '/opt/voyo/cookies-003.txt' },
];

const SUPABASE_URL  = process.env.VOYO_SUPABASE_URL  || 'https://anmgyxhnyhbyxzpjhxgx.supabase.co';
const SUPABASE_KEY  = process.env.VOYO_SUPABASE_ANON_KEY || '';
const HOSTNAME      = require('os').hostname();

// YouTube auth-gated page — if we can load this without a redirect to sign-in, session is alive
const YT_AUTH_URL   = 'https://www.youtube.com/feed/subscriptions';
const YT_HOME_URL   = 'https://www.youtube.com/';
const TIMEOUT_MS    = 30_000;

// ── Supabase event poster ─────────────────────────────────────────────────────

function postEvent(subtype, meta) {
  if (!SUPABASE_KEY) return Promise.resolve();
  const body = JSON.stringify({
    event_type: 'critical_alert',
    track_id: '-',
    meta: { subtype, source: 'session-guardian', host: HOSTNAME, ...meta },
    user_agent: 'voyo-session-guardian/1.0',
    session_id: `vps_guardian_${HOSTNAME}`,
  });
  return new Promise((resolve) => {
    const req = https.request(
      `${SUPABASE_URL}/rest/v1/voyo_playback_events`,
      {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'apikey': SUPABASE_KEY,
          'Authorization': `Bearer ${SUPABASE_KEY}`,
          'Prefer': 'return=minimal',
          'Content-Length': Buffer.byteLength(body),
        },
      },
      (res) => { res.resume(); resolve(); }
    );
    req.on('error', () => resolve());
    req.setTimeout(5000, () => { req.destroy(); resolve(); });
    req.write(body);
    req.end();
  });
}

// ── Cookie → Netscape format ──────────────────────────────────────────────────

function toNetscape(cookies) {
  const lines = ['# Netscape HTTP Cookie File', '# Generated by voyo-session-guardian'];
  for (const c of cookies) {
    // Only export YouTube cookies
    if (!c.domain.includes('youtube.com') && !c.domain.includes('google.com')) continue;
    const domain   = c.domain.startsWith('.') ? c.domain : `.${c.domain}`;
    const include  = 'TRUE';
    const path_    = c.path || '/';
    const secure   = c.secure ? 'TRUE' : 'FALSE';
    const expiry   = c.expires && c.expires > 0 ? Math.floor(c.expires) : 0;
    lines.push([domain, include, path_, secure, expiry, c.name, c.value].join('\t'));
  }
  return lines.join('\n') + '\n';
}

// ── Profile check ─────────────────────────────────────────────────────────────

async function checkProfile(profile) {
  const log = (msg) => console.log(`[${profile.name}] ${msg}`);

  if (!fs.existsSync(profile.dir)) {
    log('profile directory missing — skip');
    return { status: 'missing' };
  }

  let context;
  try {
    context = await chromium.launchPersistentContext(profile.dir, {
      headless: true,
      args: [
        '--no-sandbox',
        '--disable-setuid-sandbox',
        '--disable-dev-shm-usage',
        '--disable-blink-features=AutomationControlled',
        '--user-agent=Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36',
      ],
      ignoreHTTPSErrors: true,
      timeout: TIMEOUT_MS,
    });

    const page = await context.newPage();

    // Mask automation signals
    await page.addInitScript(() => {
      Object.defineProperty(navigator, 'webdriver', { get: () => undefined });
    });

    log('navigating to YouTube subscriptions...');
    const response = await page.goto(YT_AUTH_URL, {
      waitUntil: 'domcontentloaded',
      timeout: TIMEOUT_MS,
    }).catch(() => null);

    const finalUrl = page.url();
    log(`landed on: ${finalUrl}`);

    // If redirected to accounts.google.com or /signin — session dead
    const isLoginPage = finalUrl.includes('accounts.google.com') ||
                        finalUrl.includes('/signin') ||
                        finalUrl.includes('ServiceLogin');

    if (isLoginPage) {
      log('DEAD — redirected to sign-in page');
      await context.close();
      return { status: 'dead' };
    }

    // Check for avatar (ytd-topbar-menu-button-renderer) vs sign-in button
    const hasAvatar = await page.$('button#avatar-btn, ytd-topbar-menu-button-renderer').catch(() => null);
    const hasSignIn = await page.$('a[href*="ServiceLogin"], paper-button:has-text("Sign in")').catch(() => null);

    if (!hasAvatar || hasSignIn) {
      log('DEAD — no avatar found or sign-in button visible');
      await context.close();
      return { status: 'dead' };
    }

    log('ALIVE — session valid');

    // Warm the session: briefly visit home too (keeps session fresh)
    await page.goto(YT_HOME_URL, { waitUntil: 'domcontentloaded', timeout: TIMEOUT_MS }).catch(() => {});
    await page.waitForTimeout(2000);

    // Export fresh cookies
    const cookies = await context.cookies();
    const ytCookies = cookies.filter(c =>
      c.domain.includes('youtube.com') || c.domain.includes('google.com')
    );
    log(`exporting ${ytCookies.length} cookies → ${profile.cookieFile}`);
    fs.writeFileSync(profile.cookieFile, toNetscape(cookies), { mode: 0o600 });

    // Check SAPISID present (critical auth cookie)
    const hasSapisid = ytCookies.some(c => c.name === 'SAPISID');
    if (!hasSapisid) {
      log('WARNING — SAPISID missing from exported cookies (partial session?)');
    }

    await context.close();
    return { status: 'alive', cookieCount: ytCookies.length, hasSapisid };

  } catch (err) {
    log(`ERROR — ${err.message}`);
    try { await context?.close(); } catch {}
    return { status: 'error', error: err.message };
  }
}

// ── Main ──────────────────────────────────────────────────────────────────────

async function main() {
  console.log(`\n==== VOYO Session Guardian — ${new Date().toISOString()} ====`);

  const results = {};
  let deadCount = 0;

  for (const profile of PROFILES) {
    const result = await checkProfile(profile);
    results[profile.name] = result;
    if (result.status === 'dead') deadCount++;

    if (result.status === 'alive') {
      await postEvent('session_ok', {
        profile: profile.name,
        cookieCount: result.cookieCount,
        hasSapisid: result.hasSapisid,
      });
    } else if (result.status === 'dead') {
      console.error(`[CRITICAL] ${profile.name} is logged out — needs manual re-login`);
      await postEvent('cookie_login_lost', { profile: profile.name });
    } else if (result.status === 'missing') {
      // Profile dir doesn't exist — silently skip, not an error
    } else {
      await postEvent('cookie_login_lost', { profile: profile.name, error: result.error });
    }

    // Brief pause between profiles to avoid hammering Google
    await new Promise(r => setTimeout(r, 3000));
  }

  console.log('\n── Summary ──');
  for (const [name, r] of Object.entries(results)) {
    console.log(`  ${name}: ${r.status}${r.cookieCount ? ` (${r.cookieCount} cookies)` : ''}`);
  }

  if (deadCount > 0) {
    console.error(`\n[ACTION REQUIRED] ${deadCount} profile(s) logged out.`);
    console.error('SSH in and re-authenticate via Chrome remote debug:');
    console.error('  ssh -L 9222:localhost:9222 vps');
    console.error('  # open chrome://inspect in local browser');
  }

  console.log('\n==== done ====\n');
  process.exit(deadCount > 0 ? 1 : 0);
}

main().catch((err) => {
  console.error('guardian fatal:', err);
  process.exit(2);
});
